#include <gtest/gtest.h>

#include "PPMReader.h"

#include "ImageCh.h"

std::filesystem::path TESTS_DATA(RESOURCE_DIR);

TEST(TEST_PPM_READER, READ_8x8) {
    std::ifstream PPM_fstream(TESTS_DATA / "8x8.ppm");
    EXPECT_TRUE(PPM_fstream.is_open());
    
    PPMImageData data;
    auto res = readPPM(PPM_fstream, data);

    ASSERT_EQ(data[0], ImageCh<u8>(8, 8, {
        0,0,0,0,255,255,255,255,
0,0,0,0,255,255,255,255,
0,0,255,255,0,0,255,255,
0,0,255,255,0,0,255,255,
0,0,0,0,255,255,255,255,
0,0,0,0,255,255,255,255,
0,0,255,255,0,0,255,255,
0,0,255,255,0,0,255,255
    }));

    ASSERT_EQ(data[1], ImageCh<u8>(8, 8, {
        0,0,255,255,0,0,255,255,
0,0,255,255,0,0,255,255,
255,255,255,255,0,0,0,0,
255,255,255,255,0,0,0,0,
0,0,255,255,0,0,255,255,
0,0,255,255,0,0,255,255,
255,255,255,255,0,0,0,0,
255,255,255,255,0,0,0,0,
    }));

    ASSERT_EQ(data[2], ImageCh<u8>(8, 8, {
        255,255,0,0,0,0,0,0,
255,255,0,0,0,0,0,0,
255,255,255,255,0,0,255,255,
255,255,255,255,0,0,255,255,
255,255,0,0,0,0,0,0,
255,255,0,0,0,0,0,0,
255,255,255,255,0,0,255,255,
255,255,255,255,0,0,255,255,
    }));


}
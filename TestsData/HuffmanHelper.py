# --- Helper Functions ---
def category(value):
    if value == 0:
        return 0
    return int(math.floor(math.log2(abs(value)))) + 1

def amplitude_bits(value, size):
    if size == 0:
        return ""
    if value >= 0:
        return format(value, f"0{size}b")
    else:
        return format((1 << size) + value - 1, f"0{size}b")

def jpeg_huffman_encode(DC, ACs):
    """Encode one block with JPEG baseline Huffman (luminance)."""
    bitstream = ""

    # --- DC ---
    dc_size = category(DC)
    bitstream += DC_LUMA_HUFFMAN[dc_size]
    bitstream += amplitude_bits(DC, dc_size)

    # --- AC ---
    for run, size, value in ACs:
        if (run, size) == (0, 0):  # EOB
            bitstream += AC_LUMA_HUFFMAN[(0, 0)]
            break
        if (run, size) == (15, 0):  # ZRL
            bitstream += AC_LUMA_HUFFMAN[(15, 0)]
            continue

        huff = AC_LUMA_HUFFMAN.get((run, size))
        if huff is None:
            raise ValueError(f"No Huffman code for (run={run}, size={size})")

        bitstream += huff
        bitstream += amplitude_bits(value, size)

    return bitstream

